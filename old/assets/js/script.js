const optionalLinks = {
  cv: "",
  scholar: ""
};

const root = document.documentElement;
const langToggle = document.getElementById("langToggle");
const translatableNodes = document.querySelectorAll("[data-i18n]");
const revealNodes = document.querySelectorAll(".reveal");

let currentLang = localStorage.getItem("homepage-lang") || "en";

function applyLanguage(lang) {
  const copy = translations[lang];
  if (!copy) {
    return;
  }

  translatableNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (copy[key]) {
      node.textContent = copy[key];
    }
  });

  root.lang = lang === "zh" ? "zh-CN" : "en";
  document.title = lang === "zh" ? "吕景亭 | 生物信息学研究者" : "Jingting Lv | Bioinformatics Researcher";
  langToggle.textContent = lang === "zh" ? "EN" : "中文";
  currentLang = lang;
  localStorage.setItem("homepage-lang", lang);
}

function applyOptionalLinks() {
  document.querySelectorAll("[data-optional-link]").forEach((node) => {
    const key = node.dataset.optionalLink;
    const href = optionalLinks[key];
    if (href) {
      node.href = href;
      node.classList.remove("is-hidden");
    }
  });
}

function setupReveal() {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.16 }
  );

  revealNodes.forEach((node) => observer.observe(node));
}

langToggle.addEventListener("click", () => {
  applyLanguage(currentLang === "en" ? "zh" : "en");
});

applyLanguage(currentLang);
applyOptionalLinks();
setupReveal();
